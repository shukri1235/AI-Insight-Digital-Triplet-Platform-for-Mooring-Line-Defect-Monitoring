"""TEST DOUBLE for google.genai (structured-output report generation).

Records every request (text parts + number of images) and answers with a report built
from the facts packet it was given. FAKE_GEMINI_MODE controls behaviour:
  ok            correct, grounded report (default)
  hallucinate   first answer quotes a wrong depth and an unknown event; second answer is correct
  always_bad    every answer is ungrounded (tests NEEDS_REVIEW)
  auth_error    every call fails like Google's 401 for an unsupported (AQ.) key
  Gemini 2.5 models answer 404 "no longer available to new users" when FAKE_GEMINI_RETIRED=1
  FAKE_GEMINI_BUSY=<model,...>      those models answer 503 UNAVAILABLE "high demand" (like Oct 2026 in the field)
  FAKE_GEMINI_TIMEOUT=<model,...>   those models never answer in time (raises a ReadTimeout)
Usage: ~4 characters per text token; images 1,120 tokens each on Gemini 3 (default media resolution), 258 on older models.
"""
import json
import os

from . import types  # noqa: F401  (re-exported like the real SDK)

REQUESTS: list[dict] = []


class _Usage:
    def __init__(self, prompt, out, thoughts):
        self.prompt_token_count, self.candidates_token_count, self.thoughts_token_count = prompt, out, thoughts
        self.total_token_count = prompt + out + thoughts


class _Resp:
    def __init__(self, text, usage=None):
        self.text = text
        self.usage_metadata = usage


def _report(facts: dict, bad: bool) -> dict:
    findings = []
    for e in facts["events"]:
        findings.append({"event_ref": e["id"], "defect_type": e["type"],
                         "visual_assessment": "CONFIRMED" if e.get("keyframe") else "NOT_ASSESSED",
                         "description": f"{e['type'].title()} at {e['depth_m']} m, peak {round(e['peak_confidence'] * 100)}%."
                         if e["depth_m"] is not None else f"{e['type'].title()} (no depth recorded).",
                         "depth_m": e["depth_m"], "segment": e["segment"]})
    deform = [e for e in facts["events"] if e["type"] == "DEFORMATION"]
    grade = "REPAIR" if deform else ("MONITOR" if facts["events"] else "ACCEPTABLE")
    out = {"summary": f"{len(facts['events'])} defect events reviewed (test double).",
           "condition_grade": grade, "grade_rationale": "Test double rationale.",
           "findings": findings,
           "recommended_actions": [{"action": "VERIFY_DETECTION_MANUALLY", "priority": "IMMEDIATE",
                                    "justification": "Confirm the detection.", "refs": [e["id"] for e in deform]}],
           "limitations": ["Generated by the test double."]}
    if bad:
        out["summary"] += " The worst damage is at 999 m."
        out["findings"].append({"event_ref": "EV-99", "defect_type": "CORROSION", "visual_assessment": "CONFIRMED",
                                "description": "invented", "depth_m": 5.0, "segment": "Splash Zone"})
    return out


class ReadTimeout(Exception):
    """Same class name as httpx's, which the SDK raises when the request timeout passes."""


BUSY_CALLS: list[str] = []


class _Api:
    closed = False


class _Models:
    def __init__(self, api):
        self._api = api

    def generate_content(self, model, contents, config=None):
        if self._api.closed:      # like google-genai >= 1.x: the Client closes its HTTP client when garbage-collected
            raise RuntimeError("Cannot send a request, as the client has been closed.")
        if os.environ.get("FAKE_GEMINI_RETIRED") == "1" and model.startswith("gemini-2.5"):
            raise RuntimeError(f"404 NOT_FOUND. {{'error': {{'code': 404, 'message': 'This model models/{model} is no longer available "
                               f"to new users. Please update your code to use models/gemini-3.8-flash for the latest features and "
                               f"improvements.', 'status': 'NOT_FOUND'}}}}")
        if os.environ.get("FAKE_GEMINI_MODE") == "auth_error":
            raise RuntimeError("401 UNAUTHENTICATED. {'error': {'code': 401, 'message': 'Request had invalid authentication "
                               "credentials. Expected OAuth 2 access token, login cookie or other valid authentication "
                               "credential.', 'status': 'UNAUTHENTICATED', 'details': [{'reason': 'ACCESS_TOKEN_TYPE_UNSUPPORTED'}]}}")
        busy = [m.strip() for m in os.environ.get("FAKE_GEMINI_BUSY", "").split(",") if m.strip()]
        if model in busy:
            BUSY_CALLS.append(model)
            raise RuntimeError("503 UNAVAILABLE. {'error': {'code': 503, 'message': 'This model is currently experiencing high "
                               "demand. Spikes in demand are usually temporary. Please try again later.', 'status': 'UNAVAILABLE'}}")
        if model in [m.strip() for m in os.environ.get("FAKE_GEMINI_TIMEOUT", "").split(",") if m.strip()]:
            BUSY_CALLS.append(model)
            raise ReadTimeout("The read operation timed out")
        if isinstance(contents, str):                       # connection test
            return _Resp("OK", _Usage(len(contents) // 4, 1, 0))
        texts = [c for c in contents if isinstance(c, str)]
        images = [c for c in contents if not isinstance(c, str)]
        REQUESTS.append({"model": model, "texts": texts, "images": len(images), "temperature": getattr(config, "temperature", None),
                         "thinking": getattr(getattr(config, "thinking_config", None), "thinking_level", None),
                         "system": getattr(config, "system_instruction", None),
                         "schema": getattr(config, "response_schema", None)})
        facts = json.loads(texts[0].split("\n", 1)[1])
        mode = os.environ.get("FAKE_GEMINI_MODE", "ok")
        retry = any(t.startswith("Your previous draft failed") for t in texts)
        bad = mode == "always_bad" or (mode == "hallucinate" and not retry)
        out = json.dumps(_report(facts, bad))
        # deterministic stand-in for Gemini's usage_metadata: ~4 chars/token; per image 1,120 tokens on Gemini 3
        # (default media resolution, measured in the field: 2 images + ~1,900 text tokens = ~4,150) and 258 on Gemini 2.x
        per_image = 1120 if model.startswith("gemini-3") else 258
        return _Resp(out, _Usage(sum(len(t) for t in texts) // 4 + per_image * len(images), len(out) // 4, 100))


class _ModelInfo:
    def __init__(self, name, actions):
        self.name, self.supported_actions = name, actions


class Client:
    last_http_options = None

    def __init__(self, api_key=None, http_options=None):
        self.api_key = api_key
        Client.last_http_options = http_options
        self._api = _Api()
        self.models = _Models(self._api)
        self.models.list = lambda: [_ModelInfo("models/gemini-3.8-flash", ["generateContent"]),
                                    _ModelInfo("models/gemini-3.5-flash-lite", ["generateContent"]),
                                    _ModelInfo("models/gemini-embedding-001", ["embedContent"])]

    def close(self):
        self._api.closed = True

    def __del__(self):
        self._api.closed = True
