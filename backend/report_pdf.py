def render_pdf(view: dict, template: dict) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_RIGHT
    from reportlab.lib.pagesizes import A4, LETTER
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.lib.utils import ImageReader
    from reportlab.pdfgen import canvas as rl_canvas
    from reportlab.platypus import (CondPageBreak, Image, KeepTogether, PageBreak, Paragraph, SimpleDocTemplate, Spacer,
                                    Table, TableStyle)

    t = merge(template)
    c, g = view["content"], view.get("grounding") or {}
    sec = t["sections"]
    reg, bold, uni = fonts(t)
    accent, ink, muted = colors.HexColor(t["accent"]), colors.HexColor(t["text"]), colors.HexColor(t["muted"])
    light = colors.Color(accent.red, accent.green, accent.blue, alpha=0.08)
    size = float(t["base_size"])
    page = A4 if t["paper"] == "A4" else LETTER
    W, H = page
    margin = 18 * mm
    tdir = templates_dir()
    logo_path = (tdir / t["logo"]) if t.get("logo") and (tdir / t["logo"]).exists() else None

    def tx(s) -> str:
        s = "" if s is None else str(s)
        if not uni:
            s = "".join(_ASCII.get(ch, ch) for ch in s).encode("latin-1", "replace").decode("latin-1")
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\n", "<br/>")

    def human(s) -> str:
        return str(s or "").replace("_", " ").lower().capitalize()

    st = {
        "body": ParagraphStyle("body", fontName=reg, fontSize=size, leading=size * 1.45, textColor=ink),
        "small": ParagraphStyle("small", fontName=reg, fontSize=size - 1.5, leading=(size - 1.5) * 1.4, textColor=muted),
        "cell": ParagraphStyle("cell", fontName=reg, fontSize=size - 1, leading=(size - 1) * 1.35, textColor=ink),
        "cellb": ParagraphStyle("cellb", fontName=bold, fontSize=size - 1, leading=(size - 1) * 1.35, textColor=ink),
        "th": ParagraphStyle("th", fontName=bold, fontSize=size - 1.5, leading=(size - 1.5) * 1.3, textColor=colors.white),
        "h1": ParagraphStyle("h1", fontName=bold, fontSize=size + 12, leading=(size + 12) * 1.2, textColor=ink),
        "h2": ParagraphStyle("h2", fontName=bold, fontSize=size + 3, leading=(size + 3) * 1.3, textColor=accent,
                             spaceBefore=size * 1.4, spaceAfter=size * 0.5, keepWithNext=1),
        "label": ParagraphStyle("label", fontName=bold, fontSize=size - 2, leading=(size - 2) * 1.3, textColor=muted),
        "right": ParagraphStyle("right", fontName=reg, fontSize=size - 2, leading=(size - 2) * 1.35, textColor=muted,
                                alignment=TA_RIGHT),
        "rightb": ParagraphStyle("rightb", fontName=bold, fontSize=size, leading=size * 1.3, textColor=ink, alignment=TA_RIGHT),
    }
    approved = view["status"] == "APPROVED"
    content_w = W - 2 * margin
    scope = c.get("scope") or {}
    asset = c.get("asset") or {}
    an = c.get("analysis") or {}
    grade = c.get("condition_grade") or "-"
    grade_col = colors.HexColor(GRADE_COLORS.get(grade, "#4A5568"))

    # -------------------------------------------------------------- page decoration
    class NumberedCanvas(rl_canvas.Canvas):
        def __init__(self, *a, **k):
            super().__init__(*a, **k)
            self._pages = []

        def showPage(self):
            self._pages.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            n = len(self._pages)
            for state in self._pages:
                self.__dict__.update(state)
                decorate(self, self._pageNumber, n)
                super().showPage()
            super().save()

    def decorate(cv, num, total):
        cv.saveState()
        cover_page = t["cover"] and num == 1
        if not cover_page:                                   # header: logo left, company right, accent rule
            top = H - 12 * mm
            if logo_path:
                try:
                    ir = ImageReader(str(logo_path))
                    iw, ih = ir.getSize()
                    h = 10 * mm
                    w = min(45 * mm, h * iw / ih)
                    cv.drawImage(ir, margin, top - h + 2 * mm, width=w, height=w * ih / iw, mask="auto")
                except Exception:                            # noqa: BLE001
                    pass
            cv.setFillColor(ink)
            cv.setFont(bold, size - 1)
            y = top
            if t["company"]:
                cv.drawRightString(W - margin, y, _plain(t["company"], uni))
                y -= (size - 1) * 1.25
            cv.setFont(reg, size - 2.5)
            cv.setFillColor(muted)
            for line in ([t["header_text"]] if t["header_text"] else []) + [view["title"]]:
                cv.drawRightString(W - margin, y, _plain(line, uni))
                y -= (size - 2.5) * 1.3
            cv.setStrokeColor(accent)
            cv.setLineWidth(1.2)
            cv.line(margin, H - 22 * mm, W - margin, H - 22 * mm)
        cv.setFont(reg, size - 2.5)
        cv.setFillColor(muted)
        if t["footer_text"]:
            cv.drawString(margin, 10 * mm, _plain(t["footer_text"], uni)[:150])
        if t["page_numbers"]:
            cv.drawRightString(W - margin, 10 * mm, f"Page {num} of {total}")
        if t["watermark_drafts"] and not approved:
            cv.setFont(bold, 90)
            cv.setFillColor(colors.Color(0.5, 0.5, 0.5, alpha=0.08))
            cv.translate(W / 2, H / 2)
            cv.rotate(40)
            cv.drawCentredString(0, -30, "DRAFT")
        cv.restoreState()

    story = []

    def kv_table(rows, col1=34 * mm):
        data = [[Paragraph(tx(k), st["label"]), Paragraph(v if isinstance(v, str) else tx(v), st["cell"])] for k, v in rows if v]
        tb = Table(data, colWidths=[col1, content_w - col1])
        tb.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                                ("TOPPADDING", (0, 0), (-1, -1), 3), ("LINEBELOW", (0, 0), (-1, -2), 0.3, colors.HexColor("#DDE2E8"))]))
        return tb

    def badge(text, col, fsize=size + 4):
        from reportlab.pdfbase.pdfmetrics import stringWidth
        p = Paragraph(f'<font color="#FFFFFF">{tx(text)}</font>',
                      ParagraphStyle("b", fontName=bold, fontSize=fsize, leading=fsize * 1.2))
        tb = Table([[p]], colWidths=[stringWidth(_plain(text, uni), bold, fsize) + 18])
        tb.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), col), ("LEFTPADDING", (0, 0), (-1, -1), 8),
                                ("RIGHTPADDING", (0, 0), (-1, -1), 8), ("TOPPADDING", (0, 0), (-1, -1), 4),
                                ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
        tb.hAlign = "LEFT"
        return tb

    def banner(text, bg, fg="#111111"):
        tb = Table([[Paragraph(f'<font color="{fg}"><b>{tx(text)}</b></font>', st["cell"])]], colWidths=[content_w])
        tb.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(bg)), ("LEFTPADDING", (0, 0), (-1, -1), 8),
                                ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
        return tb

    drafted = "Rules (no AI)" if view["generator"] == "RULE_BASED" else human_model(view["generator"])
    test_note = "TEST DATA - simulated ROV video and telemetry. Not a record of a real inspection." if c.get("test_data") else None

    # -------------------------------------------------------------- cover
    if t["cover"]:
        story.append(Spacer(1, 18 * mm))
        if logo_path:
            try:
                ir = ImageReader(str(logo_path))
                iw, ih = ir.getSize()
                h = 22 * mm
                w = min(80 * mm, h * iw / ih)
                img = Image(str(logo_path), width=w, height=w * ih / iw)
                img.hAlign = "LEFT"
                story += [img, Spacer(1, 10 * mm)]
            except Exception:                                # noqa: BLE001
                pass
        if t["company"]:
            story.append(Paragraph(tx(t["company"]), ParagraphStyle("co", parent=st["body"], fontName=bold, fontSize=size + 2)))
            for line in t["company_lines"] or []:
                story.append(Paragraph(tx(line), st["small"]))
            story.append(Spacer(1, 16 * mm))
        story.append(Paragraph(tx(t["title"]), st["h1"]))
        story.append(Spacer(1, 4 * mm))
        story.append(Paragraph(tx(f"{human(view.get('scope_type'))} report - {scope.get('name') or view['title']}"),
                               ParagraphStyle("sub", parent=st["body"], fontSize=size + 2, leading=(size + 2) * 1.4)))
        story.append(Spacer(1, 10 * mm))
        story.append(badge(grade, grade_col, size + 8))
        story.append(Spacer(1, 8 * mm))
        story.append(kv_table([
            ("Asset", f"{asset.get('line_name') or ''} ({asset.get('line_id') or ''})"),
            ("Covers", (scope.get("coverage") or {}).get("text")),
            ("Status", human(view["status"]) + (f" - approved by {view['engineer']} on {view['approved_at']}" if approved else "")),
            ("Report date", view.get("created_at")),
            ("Report id", view["id"]),
        ], col1=30 * mm))
        if test_note:
            story += [Spacer(1, 8 * mm), banner(test_note, "#F6C344")]
        story.append(PageBreak())
    else:
        story.append(Paragraph(tx(t["title"]), st["h1"]))
        story.append(Paragraph(tx(scope.get("name") or view["title"]), st["small"]))
        story.append(Spacer(1, 4 * mm))
        if test_note:
            story += [banner(test_note, "#F6C344"), Spacer(1, 3 * mm)]

    # -------------------------------------------------------------- overview
    if sec["overview"]:
        story.append(Paragraph("Inspection overview", st["h2"]))
        sensors = c.get("sensors") or {}
        story.append(kv_table([
            ("Asset", f"{asset.get('line_name') or ''} ({asset.get('line_id') or ''})"),
            ("Scope", f"{human(view.get('scope_type'))} - {scope.get('name') or ''}"),
            ("Covers", (scope.get("coverage") or {}).get("text")),
            ("Analysis", f"{human(an.get('kind'))} run, threshold {an.get('threshold')}"
                         + (f", clip trigger {an.get('trigger_threshold')}" if an.get("trigger_threshold") else "")
                         + (f", model {an.get('model')}" if an.get("model") else "") if an else None),
            ("ROV sensors", f"{sensors.get('source')}" + (f", {sensors.get('samples')} readings" if sensors.get("samples") is not None else "")
             if sensors else None),
            ("Drafted by", drafted),
            ("Status", human(view["status"]) + (f" - approved by {view['engineer']} on {view['approved_at']}" if approved else "")),
        ]))

    # -------------------------------------------------------------- grade + summary
    if sec["summary"]:
        story.append(Paragraph("Condition and summary", st["h2"]))
        story.append(KeepTogether([badge(grade, grade_col), Spacer(1, 3 * mm),
                                   Paragraph(tx(c.get("grade_rationale")), ParagraphStyle("ra", parent=st["body"], textColor=muted))]))
        story.append(Spacer(1, 3 * mm))
        story.append(Paragraph(tx(c.get("summary")), st["body"]))

    # -------------------------------------------------------------- findings
    findings = c.get("findings") or []
    if sec["findings"]:
        story.append(CondPageBreak(40 * mm))
        story.append(Paragraph(f"Findings ({len(findings)})", st["h2"]))
        if not findings:
            story.append(Paragraph("No defect events in this scope.", st["body"]))
        else:
            head = [Paragraph(h, st["th"]) for h in ("Event", "Type", "Depth", "Segment", "Peak", "Visual check", "Description")]
            rows = [head]
            for f in findings:
                ev = f.get("event") or {}
                ftype = "Deformation" if f.get("defect_type") == "DEFORMATION" else \
                    "Pitting (grade 6–7)" if f.get("defect_type") == "CORROSION" else human(f.get("defect_type"))
                rows.append([Paragraph(tx(f.get("event_ref")) + (f"<br/>{_mmss(ev['t_start'])}" if ev.get("t_start") is not None else ""), st["cellb"]),
                             Paragraph(tx(ftype), st["cell"]),
                             Paragraph(tx(f"{f['depth_m']} m" if f.get("depth_m") is not None else "-"), st["cell"]),
                             Paragraph(tx(f.get("segment") or "-"), st["cell"]),
                             Paragraph(tx(f"{round(ev['peak_confidence'] * 100)}%" if ev.get("peak_confidence") is not None else "-"), st["cell"]),
                             Paragraph(tx(human(f.get("visual_assessment"))), st["cell"]),
                             Paragraph(tx(f.get("description")), st["cell"])])
            widths = [15 * mm, 25 * mm, 15 * mm, 23 * mm, 14 * mm, 21 * mm]
            widths.append(content_w - sum(widths))
            tb = Table(rows, colWidths=widths, repeatRows=1)
            tb.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), accent), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, light]),
                                    ("LINEBELOW", (0, 0), (-1, -1), 0.3, colors.HexColor("#DDE2E8")),
                                    ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 5)]))
            story.append(tb)

    # -------------------------------------------------------------- evidence
    kfs = c.get("keyframes") or []
    fdir = Path(view.get("frames_dir") or "")
    if sec["evidence"] and kfs:
        story.append(CondPageBreak(70 * mm))
        story.append(Paragraph("Evidence (key frames)", st["h2"]))
        by_ref = {f.get("event_ref"): f for f in findings}
        for k in kfs:
            dims = []
            for fn in k.get("files", [])[:2]:
                p = fdir / fn
                if p.exists():
                    try:
                        dims.append((p, *ImageReader(str(p)).getSize()))
                    except Exception:                        # noqa: BLE001
                        continue
            # both images the same height, together as wide as the page allows
            gap = 4 * mm
            h = min([70 * mm] + [(content_w - gap * len(dims)) / sum(iw / ih for _, iw, ih in dims)] if dims else [0])
            cells = [Image(str(p), width=h * iw / ih, height=h) for p, iw, ih in dims]
            if not cells:
                continue
            f = by_ref.get(k.get("event_ref")) or {}
            cap = (f"{k.get('event_ref')} at t = {k.get('t')} s - full frame (box drawn) and 2x close-up"
                   + (f" - {human(f.get('defect_type'))}, {f['depth_m']} m" if f.get("depth_m") is not None else ""))
            row = Table([cells], colWidths=[c_.drawWidth + gap for c_ in cells])
            row.hAlign = "LEFT"
            row.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0),
                                     ("RIGHTPADDING", (0, 0), (-1, -1), 0)]))
            story.append(KeepTogether([row, Paragraph(tx(cap), st["small"]), Spacer(1, 4 * mm)]))

    # -------------------------------------------------------------- actions
    acts = c.get("recommended_actions") or []
    if sec["actions"] and acts:
        story.append(CondPageBreak(30 * mm))
        story.append(Paragraph("Recommended actions", st["h2"]))
        rows = []
        for i, a in enumerate(acts, 1):
            pc = PRIORITY_COLORS.get(a.get("priority"), "#4A5568")
            rows.append([Paragraph(f"<b>{i}.</b>", st["cell"]),
                         Paragraph(f'<font color="{pc}"><b>{tx(human(a.get("priority")).upper())}</b></font><br/>'
                                   f"<b>{tx(human(a.get('action')))}</b>"
                                   + (f' <font color="{t["muted"]}">({tx(", ".join(a.get("refs") or []))})</font>' if a.get("refs") else "")
                                   + f"<br/>{tx(a.get('justification'))}", st["cell"])])
        tb = Table(rows, colWidths=[8 * mm, content_w - 8 * mm])
        tb.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                                ("LINEBELOW", (0, 0), (-1, -2), 0.3, colors.HexColor("#DDE2E8"))]))
        story.append(tb)

    if sec["limitations"] and c.get("limitations"):
        story.append(Paragraph("Limitations", st["h2"]))
        for x in c["limitations"]:
            story.append(Paragraph(f"&bull; {tx(x)}", st["body"]))
    story.append(Paragraph("Basis of the findings", st["h2"]))
    story.append(Paragraph(tx(BASIS_NOTE), st["body"]))
    if sec["engineer_notes"] and (c.get("engineer_notes") or "").strip():
        story.append(Paragraph("Engineer notes", st["h2"]))
        story.append(Paragraph(tx(c["engineer_notes"]), st["body"]))
    if sec["grounding"]:
        story.append(Spacer(1, 4 * mm))
        ok = g.get("passed", True)
        txt = ("Grounding check: every event, depth and segment in this report was checked by code against the "
               "inspection database." if ok else "Grounding check FAILED: " + "; ".join(g.get("errors") or []))
        story.append(banner(txt, "#E6F4EE" if ok else "#FDECEC", "#1B5E43" if ok else "#9B2C2C"))
    if sec["ai_usage"] and (c.get("usage") or c.get("timings")):
        u, tm = c.get("usage") or {}, c.get("timings") or {}
        story.append(Paragraph("Report metadata", st["h2"]))
        story.append(kv_table([
            ("AI usage", f"{u.get('requests')} request(s), {u.get('input')} input / {u.get('output')} output / "
                         f"{u.get('thinking')} thinking tokens" if u else None),
            ("Time taken", f"{tm.get('total')} s" + (f" (Gemini {tm.get('ai')} s)" if isinstance(tm.get("ai"), (int, float)) else "")
             if tm.get("total") is not None else None),
        ]))
    if sec["sign_off"]:
        so = t["sign_off"]
        story.append(CondPageBreak(32 * mm))
        story.append(Paragraph("Sign-off", st["h2"]))
        line = "_" * 34 if so["signature_lines"] else ""
        cells = [[Paragraph(f"<b>{tx(so['prepared_label'])}</b><br/>{tx(drafted)}<br/><br/>{line}", st["cell"]),
                  Paragraph(f"<b>{tx(so['approved_label'])}</b><br/>"
                            + (f"{tx(view['engineer'])}<br/>{tx(view['approved_at'])}" if approved else "Not yet approved<br/>")
                            + f"<br/>{line}", st["cell"])]]
        tb = Table(cells, colWidths=[content_w / 2] * 2)
        tb.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0)]))
        story.append(tb)
    if t["disclaimer"]:
        story.append(Spacer(1, 6 * mm))
        story.append(Paragraph(tx(t["disclaimer"]), st["small"]))

    buf = io.BytesIO()
    top = 26 * mm
    doc = SimpleDocTemplate(buf, pagesize=page, leftMargin=margin, rightMargin=margin, topMargin=top, bottomMargin=18 * mm,
                            title=_plain(view["title"], True), author=_plain(t["company"] or "AI Insights Digital Triplet Platform", True),
                            subject="Mooring line inspection report", creator="AI Insights Digital Triplet Platform")
    doc.build(story, canvasmaker=NumberedCanvas)
    return buf.getvalue()


def _plain(s, uni) -> str:
    s = "" if s is None else str(s)
    if not uni:
        s = "".join(_ASCII.get(ch, ch) for ch in s).encode("latin-1", "replace").decode("latin-1")
    return s


def _mmss(t) -> str:
    try:
        return f"{int(t // 60)}:{int(t % 60):02d}"
    except TypeError:
        return ""


def human_model(m: str) -> str:
    return " ".join(w.capitalize() for w in re.split(r"[-_]", m or ""))


def file_name(view: dict, template: dict) -> str:
    base = re.sub(r"[^A-Za-z0-9_.-]+", "_", (view["content"].get("scope") or {}).get("name") or view["title"]).strip("_")
    base = re.sub(r"\.(mp4|mov|mkv|avi)$", "", base, flags=re.I)
    return f"{base[:80]}_{view['status'].lower()}.pdf"


