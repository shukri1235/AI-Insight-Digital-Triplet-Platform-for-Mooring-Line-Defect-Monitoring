# ------------------------------------------------------------------------------------------- templates
def templates_dir() -> Path:
    d = Path(REPORT_TEMPLATES_DIR)
    d.mkdir(parents=True, exist_ok=True)
    if not (d / "default.json").exists():
        (d / "default.json").write_text(json.dumps(DEFAULT_TEMPLATE, indent=2), encoding="utf-8")
    readme = d / "README.txt"
    if not readme.exists():
        readme.write_text(
            "PDF report templates for the AI Insights Digital Triplet Platform.\n"
            "One <id>.json per template (id: lower-case letters, digits, - and _). Edit them in the app\n"
            "(System -> Report templates) or here; every field is optional (see default.json for all of them).\n"
            "logo: a PNG or JPG file in this folder. font: auto, helvetica, times, or the path of a .ttf file\n"
            "(set font_bold too). Colours are #RRGGBB.\n", encoding="utf-8")
    return d


def merge(t: dict) -> dict:
    out = json.loads(json.dumps(DEFAULT_TEMPLATE))
    for k, v in (t or {}).items():
        if k in ("sections", "sign_off") and isinstance(v, dict):
            out[k].update({kk: vv for kk, vv in v.items() if kk in out[k]})
        elif k in out:
            out[k] = v
    return out


def validate(t: dict) -> list[str]:
    errs = []
    for k in ("accent", "text", "muted"):
        if t.get(k) and not HEX_RE.match(str(t[k])):
            errs.append(f"{k} must be a colour like #0E7C66")
    if t.get("paper") not in ("A4", "Letter"):
        errs.append("paper must be A4 or Letter")
    try:
        if not 7 <= float(t.get("base_size", 10)) <= 14:
            errs.append("base_size must be 7-14 pt")
    except (TypeError, ValueError):
        errs.append("base_size must be a number")
    f = str(t.get("font") or "auto")
    if f.lower() not in ("auto", "helvetica", "times") and not (f.lower().endswith(".ttf") and Path(f).exists()):
        errs.append(f"font: {f} is not auto / helvetica / times or an existing .ttf file")
    if t.get("logo") and not (templates_dir() / str(t["logo"])).exists():
        errs.append(f"logo file {t['logo']} is not in the templates folder")
    if not isinstance(t.get("company_lines", []), list):
        errs.append("company_lines must be a list of lines")
    return errs


def load(tid: str) -> dict:
    p = templates_dir() / f"{tid}.json"
    if not ID_RE.match(tid or "") or not p.exists():
        raise KeyError(tid)
    try:
        raw = json.loads(p.read_text(encoding="utf-8-sig"))
    except ValueError as e:
        raise ValueError(f"{p.name} is not valid JSON: {e}") from e
    return {**merge(raw), "id": tid}


def list_templates() -> list[dict]:
    out = []
    for p in sorted(templates_dir().glob("*.json")):
        tid = p.stem
        if not ID_RE.match(tid):
            continue
        try:
            t = load(tid)
            out.append({**t, "errors": validate(t)})
        except (KeyError, ValueError) as e:
            out.append({"id": tid, "name": tid, "errors": [str(e)]})
    return out


def save(tid: str, data: dict) -> dict:
    if not ID_RE.match(tid or ""):
        raise ValueError("Template id: lower-case letters, digits, - and _ (max 41 characters)")
    t = merge({k: v for k, v in data.items() if k != "id"})
    errs = validate(t)
    if errs:
        raise ValueError("; ".join(errs))
    (templates_dir() / f"{tid}.json").write_text(json.dumps({k: v for k, v in t.items() if k != "id"}, indent=2),
                                                 encoding="utf-8")
    return {**t, "id": tid}


def delete(tid: str):
    if tid == "default":
        raise ValueError("The default template cannot be deleted (edit it instead)")
    t = load(tid)
    (templates_dir() / f"{tid}.json").unlink()
    if t.get("logo") and not any(o.get("logo") == t["logo"] for o in list_templates()):
        (templates_dir() / t["logo"]).unlink(missing_ok=True)


def save_logo(tid: str, filename: str, data: bytes) -> dict:
    ext = Path(filename or "").suffix.lower()
    if ext not in LOGO_EXT:
        raise ValueError("Logo must be a PNG or JPG file")
    if len(data) > 3 * 1024 * 1024:
        raise ValueError("Logo must be smaller than 3 MB")
    from PIL import Image
    try:
        Image.open(io.BytesIO(data)).verify()
    except Exception as e:                                   # noqa: BLE001
        raise ValueError(f"Not a readable image: {e}") from e
    t = load(tid)
    name = f"{tid}-logo{'.jpg' if ext == '.jpeg' else ext}"
    for old in templates_dir().glob(f"{tid}-logo.*"):
        old.unlink(missing_ok=True)
    (templates_dir() / name).write_bytes(data)
    t["logo"] = name
    return save(tid, t)


def default_id() -> tuple[str, str]:
    try:
        chosen = (json.loads(SETTINGS_FILE.read_text(encoding="utf-8")).get("report_template") or "").strip()
    except (OSError, ValueError):
        chosen = ""
    import os
    import config as cfg
    configured = "report.template" in cfg.CONFIG_STATUS["used"] or bool(os.environ.get("FYP_REPORT_TEMPLATE"))
    for tid, src in ((chosen, "chosen in the app"), (REPORT_TEMPLATE_DEFAULT if configured else "", "config file"),
                     ("default", "built-in")):
        if tid and (templates_dir() / f"{tid}.json").exists():
            return tid, src
    return "default", "built-in"


