def fonts(t: dict) -> tuple[str, str, bool]:
    """(regular, bold, unicode) font names registered with reportlab. unicode=False -> Latin-1 only (Helvetica)."""
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    want = str(t.get("font") or "auto")
    if want.lower() == "helvetica":
        return "Helvetica", "Helvetica-Bold", False
    if want.lower() == "times":
        return "Times-Roman", "Times-Bold", False
    pairs = [(want, t.get("font_bold") or want)] if want.lower().endswith(".ttf") else _SYSTEM_FONTS
    for reg, bold in pairs:
        if (reg, bold) in _FONT_CACHE:
            return _FONT_CACHE[(reg, bold)]
        if Path(reg).exists():
            try:
                n = f"T{len(_FONT_CACHE)}"
                pdfmetrics.registerFont(TTFont(n, reg))
                pdfmetrics.registerFont(TTFont(n + "B", bold if Path(bold).exists() else reg))
                _FONT_CACHE[(reg, bold)] = (n, n + "B", True)
                return _FONT_CACHE[(reg, bold)]
            except Exception:                                # noqa: BLE001 - a broken font file: try the next
                continue
    return "Helvetica", "Helvetica-Bold", False


